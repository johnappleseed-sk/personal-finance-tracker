package com.personalfinance.report;

import java.math.BigDecimal;
import java.util.List;

import com.personalfinance.account.AccountCurrency;
import com.personalfinance.category.CategoryType;

/** Detached MIS & Decision Support System (DSS) report view for a selected currency. */
public record ReportView(
		AccountCurrency selectedCurrency,
		List<AccountCurrency> availableCurrencies,
		List<MonthlyTrendPoint> monthlyTrends,
		List<CategoryAnalyticsRow> categoryAnalytics,
		DssSummary dssSummary
) {

	/** One month of income, expense, net cash flow, and savings rate for trend analysis. */
	public record MonthlyTrendPoint(
			String month,
			BigDecimal income,
			BigDecimal expense,
			BigDecimal netCashFlow,
			int savingsRatePercent,
			int incomeBarPercent,
			int expenseBarPercent
	) {
	}

	/** Aggregated MIS metrics per category for the selected currency. */
	public record CategoryAnalyticsRow(
			String categoryName,
			CategoryType categoryType,
			int transactionCount,
			BigDecimal totalAmount,
			BigDecimal averageAmount,
			int sharePercent
	) {
	}

	/** Decision Support System (DSS) KPIs and data-driven recommendations. */
	public record DssSummary(
			BigDecimal currentLiquidity,
			BigDecimal sixMonthIncome,
			BigDecimal sixMonthExpense,
			BigDecimal sixMonthNetSavings,
			BigDecimal avgMonthlyExpense,
			int overallSavingsRatePercent,
			String topExpenseCategory,
			BigDecimal topExpenseAmount,
			String healthStatus,
			String healthBadgeClass,
			List<DssRecommendation> recommendations
	) {
	}

	/** Actionable decision card generated by the DSS rule engine. */
	public record DssRecommendation(
			String title,
			String badgeLabel,
			String badgeClass,
			String dataFinding,
			String recommendedDecision
	) {
	}
}
